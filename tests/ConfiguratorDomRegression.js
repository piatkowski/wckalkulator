    const dom = new JSDOM('<body><div id="wpwrap"></div><form id="post"><input type="hidden" name="_wck_fieldset"><input class="expression_type expression_off" type="radio" name="_wck_choose_expression_type" value="off" checked><ul id="f-field-list"></ul><select id="wck-parameters"><optgroup class="defined-fields"></optgroup><optgroup class="global-parameters"></optgroup></select></form></body>', {runScripts: 'outside-only'});
    const window = dom.window, $ = require('jquery')(window);
    window.jQuery = $;
    ['sortable', 'iris', 'tipTip', 'autocomplete'].forEach(method => { $.fn[method] = function () { return this; }; });
    window.alert = message => { throw new Error(message); };
    window.confirm = () => true;
