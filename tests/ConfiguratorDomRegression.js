'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {execFileSync} = require('node:child_process');
const {JSDOM} = require('jsdom');
const root = path.resolve(__dirname, '..');
const html = execFileSync('php', ['-n', path.join(__dirname, 'support/RenderConfiguratorPreview.php')], {encoding: 'utf8'});
async function run(asset) {
    const dom = new JSDOM(html.replace(/<script\b[^>]*>[\s\S]*?<\/script>/g, ''), {runScripts: 'outside-only'});
    const window = dom.window;
    const $ = require('jquery')(window);
    window.jQuery = $;
    window.wck_configurator_i18n = {step: 'Step %1$s of %2$s', rows: 'Rows %s', limit: 'Row limit', measurement: 'Bad measurement', required: 'Required'};
    window.eval(fs.readFileSync(path.join(root, 'assets/js', asset), 'utf8'));
    await new Promise(resolve => $(resolve));
    let passed = 0;
    function check(message, condition) { assert.ok(condition, asset + ': ' + message); passed++; }
    const first = $('#product-1'), second = $('#product-2');
    check('only first step displayed', first.find('.wck-step').first().prop('hidden') === false && first.find('.wck-step').last().prop('hidden') === true);
    check('progress is available', first.find('.wck-step-progress').prop('hidden') === false);
    first.find('.wck-step-next').trigger('click');
    check('valid first step advances', first.find('.wck-step').first().prop('hidden') === true);
    first.find('.wck-step-back').trigger('click');
    check('Back restores entered values', first.find('input[name="wck[items][0][width][value]"]').val() === '100');
    first.find('.wck-add-row').trigger('click');
    check('add row affects only its form', first.find('.wck-repeat-row').length === 3 && second.find('.wck-repeat-row').length === 2);
    check('clone has correctly indexed name', first.find('input[name="wck[items][2][width][value]"]').length === 1);
    check('clone identifiers do not retain placeholder', first.find('.wck-repeat-row [id]').toArray().every(el => !el.id.includes('__row__')));
    check('empty required clone blocks Next', first.find('.wck-step-next').trigger('click') && !first.find('.wck-step').first().prop('hidden'));
    first.find('.wck-repeat-row').eq(1).find('.wck-remove-row').trigger('click');
    check('remove renumbers following rows', first.find('input[name="wck[items][1][width][value]"]').length === 1 && first.find('input[name="wck[items][2][width][value]"]').length === 0);
    const ids = $('input[id], select[id], textarea[id]').toArray().map(el => el.id);
    check('IDs are unique across forms', new Set(ids).size === ids.length);
    check('labels resolve to their controls', $('label[for]').toArray().every(el => window.document.getElementById(el.htmlFor)));
    first.find('input[name="wck[items][0][width][value]"]').val('1.5').trigger('input');
    check('measurement step is validated after conversion', !first.find('input[name="wck[items][0][width][value]"]')[0].checkValidity());
    first.find('input[name="wck[items][0][width][value]"]').val('100').trigger('input');
    check('valid measurement clears previous error', first.find('input[name="wck[items][0][width][value]"]')[0].checkValidity());
    second.find('[name="quantity"]').val('3').trigger('change');
    check('quantity creates one row per item', second.find('.wck-repeat-row').length === 3);
    check('quantity mode hides manual add and remove', second.find('.wck-add-row').prop('hidden') && second.find('.wck-remove-row').first().prop('hidden'));
    second.find('[name="quantity"]').val('6').trigger('change');
    check('quantity beyond configured maximum is invalid', !second.find('[name="quantity"]')[0].checkValidity());
    second.find('[name="quantity"]').val('1').trigger('change');
    check('decreasing quantity updates rows and clears error', second.find('.wck-repeat-row').length === 1 && second.find('[name="quantity"]')[0].checkValidity());
    const values = window.WCKConfigurator;
    check('unit conversion is consistent with PHP', values.measurementValue('100', 0.01, {min: 0, max: 10, step: 0.01, precision: 4}) === 1);
    check('decimal half tie matches PHP rounding', values.measurementValue('1.005', 1, {min: 0, max: 10, step: 0.01, precision: 2}) === 1.01);
    check('negative values cannot round to valid zero', Number.isNaN(values.measurementValue('-0.00001', 1, {min: 0, max: 10, step: 0.01, precision: 2})));
    check('zero is retained in visibility rules', values.compare([0], '2', '') && values.compare([0], '3', '0'));
    console.log(asset + ' DOM regression: ' + passed + '/' + passed + ' passed');
    window.close();
}
